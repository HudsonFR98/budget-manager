import logging
import os
from flask import Blueprint, send_from_directory, abort
from fair3r_custom_overlay.lib import config

coverage = Blueprint('coverage', __name__)
log = logging.getLogger(__name__)


@coverage.route('')
def index():
    """
    Serve the coverage report index page.
    
    This route serves the HTML coverage report generated by pytest-cov.
    The coverage report is only available in test context for security reasons.
    
    Returns:
        HTML coverage report or 404 if not in test context or report not found
    """
    # Only allow access in test context
    if config.CONTEXT != 'test':
        abort(404)
    
    # Coverage report directory
    coverage_dir = '/opt/fair3r_custom_overlay_data/coverage_report/html'
    
    # Check if coverage report exists
    if not os.path.exists(os.path.join(coverage_dir, 'index.html')):
        abort(404, description="Coverage report not found. Run tests first.")
    
    return send_from_directory(coverage_dir, 'index.html')


@coverage.route('/<path:filename>')
def static_files(filename):
    """
    Serve static files from the coverage report directory.
    
    This route serves CSS, JS, and other static files needed by the
    HTML coverage report.
    
    Args:
        filename: The filename to serve from the coverage report directory
    
    Returns:
        Static file or 404 if not in test context or file not found
    """
    # Only allow access in test context
    if config.CONTEXT != 'test':
        abort(404)
    
    # Coverage report directory
    coverage_dir = '/opt/fair3r_custom_overlay_data/coverage_report/html'
    
    # Check if file exists
    file_path = os.path.join(coverage_dir, filename)
    if not os.path.exists(file_path):
        abort(404)
    
    return send_from_directory(coverage_dir, filename) 