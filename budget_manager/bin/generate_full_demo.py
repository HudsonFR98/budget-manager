#!/usr/bin/env python3
"""Generate budget_manager/bin/full_demo.sql (deterministic demo dataset).

Loaded on validation deploys after Alembic. Re-run this script after changing
the generator, then commit the resulting SQL. Later months are filled by the
``fill_validation_demo_transactions`` scheduled task.
"""
from __future__ import annotations

import calendar
import importlib.util
import sys
from datetime import date
from pathlib import Path
from random import Random

DEMO_MONTH = Path(__file__).resolve().parents[1] / "lib" / "demo_month.py"

# Load the stdlib builder without importing the Flask app (avoids required env vars).
_spec = importlib.util.spec_from_file_location("demo_month", DEMO_MONTH)
_demo_month = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
sys.modules["demo_month"] = _demo_month
_spec.loader.exec_module(_demo_month)

BASE_RATIO = _demo_month.BASE_RATIO
BASE_START_AMOUNT = _demo_month.BASE_START_AMOUNT
BUDGETS = _demo_month.BUDGETS
CATEGORIES = _demo_month.CATEGORIES
SAVINGS = _demo_month.SAVINGS
SENTINEL_SAVING = _demo_month.SENTINEL_SAVING
SYSTEM_SAVING_NAME = _demo_month.SYSTEM_SAVING_NAME
DEMO_BUSINESS_NAME = _demo_month.DEMO_BUSINESS_NAME
DEMO_BUSINESS_STARTED_ON = _demo_month.DEMO_BUSINESS_STARTED_ON
DEMO_BUSINESS_SALES_COLOR = _demo_month.DEMO_BUSINESS_SALES_COLOR
DEMO_BUSINESS_SALES_ICON = _demo_month.DEMO_BUSINESS_SALES_ICON
DEMO_BUSINESS_EXPENSES_COLOR = _demo_month.DEMO_BUSINESS_EXPENSES_COLOR
DEMO_BUSINESS_EXPENSES_ICON = _demo_month.DEMO_BUSINESS_EXPENSES_ICON
demo_business_sales_category_name = _demo_month.demo_business_sales_category_name
demo_business_expense_category_name = _demo_month.demo_business_expense_category_name
resolve_demo_category_name = _demo_month.resolve_demo_category_name
DemoMonthBuilder = _demo_month.DemoMonthBuilder
DemoSavingsLedger = _demo_month.DemoSavingsLedger

OUTPUT = Path(__file__).with_name("full_demo.sql")
RNG = Random(20261117)
END = date(2026, 11, 17)
MONTHS = 8  # April 2026 through November 2026


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def sql_num(value: float | int) -> str:
    return f"{float(value):.2f}"


def add_months(year: int, month: int, delta: int) -> tuple[int, int]:
    total = year * 12 + (month - 1) + delta
    return total // 12, total % 12 + 1


def iter_months() -> list[tuple[int, int]]:
    year, month = add_months(END.year, END.month, -(MONTHS - 1))
    months = []
    for _ in range(MONTHS):
        months.append((year, month))
        year, month = add_months(year, month, 1)
    return months


def last_day_in_month(year: int, month: int) -> int:
    last = calendar.monthrange(year, month)[1]
    if year == END.year and month == END.month:
        return min(last, END.day)
    return last


def cat_id(name: str) -> str:
    return f"(SELECT id FROM category WHERE name = {sql_str(name)})"


def sav_id(name: str) -> str:
    return f"(SELECT id FROM saving WHERE name = {sql_str(name)})"


def build_transactions():
    ledger = DemoSavingsLedger()
    builder = DemoMonthBuilder(RNG)
    rows = []
    history = []

    for year, month in iter_months():
        last_day = last_day_in_month(year, month)
        is_current = year == END.year and month == END.month
        month_rows = builder.build(year, month, last_day=last_day, is_current=is_current)
        for row in month_rows:
            if row.kind == "income":
                ledger.apply_income(row.amount, row.saving_name)
            elif row.saving_name:
                ledger.apply_saving_expense(row.amount, row.saving_name)
        rows.extend(month_rows)
        if not is_current:
            leftover = ledger.leftover_from_rows(month_rows, year, month)
            ledger.distribute_leftover(leftover)
            history.append((date(year, month, calendar.monthrange(year, month)[1]), dict(ledger.amounts)))

    return rows, ledger.amounts, history


def render_sql() -> str:
    transactions, final_amounts, history = build_transactions()
    base_note = "Tout ce qui n'est pas de l'épargne"
    lines = [
        "-- Full demo dataset for the validation context.",
        "-- Loaded by deploy/docker-entrypoint.sh after Alembic, only when",
        "-- BUDGET_MANAGER_CONTEXT=validation. Idempotent: skipped if the Vacances saving exists.",
        "-- Later months are inserted by the fill_validation_demo_transactions scheduled task.",
        "-- Regenerated by: python3 budget_manager/bin/generate_full_demo.py",
        f"-- {len(transactions)} transactions, {len(SAVINGS) + 1} savings, {len(CATEGORIES)} extra categories.",
        "BEGIN;",
        "",
    ]

    for name, type_, color, icon in CATEGORIES:
        lines.append(
            "INSERT INTO category (name, type, color, icon)\n"
            f"SELECT {sql_str(name)}, {type_}, {sql_str(color)}, {sql_str(icon)}\n"
            f"WHERE NOT EXISTS (SELECT 1 FROM category WHERE name = {sql_str(name)});"
        )

    sales_name = demo_business_sales_category_name()
    expense_name = demo_business_expense_category_name()
    lines += [
        "",
        "-- Create one demo business when none exists (runs even if the rest of the demo is skipped).",
        "INSERT INTO category (name, type, color, icon)",
        f"SELECT {sql_str(sales_name)}, 0, {sql_str(DEMO_BUSINESS_SALES_COLOR)}, {sql_str(DEMO_BUSINESS_SALES_ICON)}",
        "WHERE NOT EXISTS (SELECT 1 FROM business)",
        f"  AND NOT EXISTS (SELECT 1 FROM category WHERE name = {sql_str(sales_name)});",
        "",
        "INSERT INTO category (name, type, color, icon)",
        f"SELECT {sql_str(expense_name)}, 2, {sql_str(DEMO_BUSINESS_EXPENSES_COLOR)}, {sql_str(DEMO_BUSINESS_EXPENSES_ICON)}",
        "WHERE NOT EXISTS (SELECT 1 FROM business)",
        f"  AND NOT EXISTS (SELECT 1 FROM category WHERE name = {sql_str(expense_name)});",
        "",
        "INSERT INTO business (name, started_on, opening_result, sales_category_id, expense_category_id)",
        f"SELECT {sql_str(DEMO_BUSINESS_NAME)}, '{DEMO_BUSINESS_STARTED_ON.isoformat()}', 0.00,",
        f"       {cat_id(sales_name)}, {cat_id(expense_name)}",
        "WHERE NOT EXISTS (SELECT 1 FROM business);",
        "",
    ]

    lines += [
        "",
        "DO $demo$",
        "BEGIN",
        f"    IF EXISTS (SELECT 1 FROM saving WHERE name = {sql_str(SENTINEL_SAVING)}) THEN",
        "        RAISE NOTICE 'Validation demo data already present; skipping.';",
        "    ELSE",
        "",
        f"    UPDATE saving SET note = {sql_str(base_note)},",
        f"        amount = {sql_num(BASE_START_AMOUNT)}, icon = '🔒', color = '#6ae76b',",
        f"        goal = NULL, ratio = {sql_num(BASE_RATIO)}",
        f"        WHERE name = {sql_str(SYSTEM_SAVING_NAME)};",
        "",
    ]

    for name, note, amount, icon, color, goal, ratio in SAVINGS:
        lines.append(
            "    INSERT INTO saving (name, note, amount, icon, color, goal, ratio)\n"
            f"    VALUES ({sql_str(name)}, {sql_str(note)}, {sql_num(amount)}, "
            f"{sql_str(icon)}, {sql_str(color)}, {sql_num(goal)}, {sql_num(ratio)});"
        )

    lines.append("")
    for category_name, percent in BUDGETS:
        lines.append(
            "    INSERT INTO budget (date, amount)\n"
            f"    VALUES ('2026-04-01', {percent:.6f});\n"
            "    INSERT INTO category_budget (category_id, budget_id)\n"
            f"    SELECT {cat_id(category_name)}, currval('budget_id_seq');"
        )

    lines.append("")
    for row in transactions:
        saving_sql = sav_id(row.saving_name) if row.saving_name else "NULL"
        category_name = resolve_demo_category_name(row.category_name, sales_name, expense_name)
        lines.append(
            "    INSERT INTO public.transaction (date, note, amount, category_id, saving_id)\n"
            f"    VALUES ('{row.date.isoformat()}', {sql_str(row.note)}, {sql_num(row.amount)}, "
            f"{cat_id(category_name)}, {saving_sql});"
        )

    lines.append("")
    for name, amount in final_amounts.items():
        lines.append(
            f"    UPDATE saving SET amount = {sql_num(amount)} WHERE name = {sql_str(name)};"
        )

    lines.append("")
    for snapshot_date, snapshot_amounts in history:
        for name, amount in snapshot_amounts.items():
            lines.append(
                "    INSERT INTO saving_history (saving_id, date, amount)\n"
                f"    VALUES ({sav_id(name)}, '{snapshot_date.isoformat()}', {sql_num(amount)});"
            )

    lines += [
        "",
        "    END IF;",
        "END",
        "$demo$;",
        "",
        "COMMIT;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUTPUT.write_text(render_sql(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
